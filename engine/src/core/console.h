// 控制台输出编码：让中文在**双击运行**时也正常显示。
//
// 问题：Windows 控制台默认用本地代码页（简中系统是 GBK / 936）解读程序输出，
// 而本项目的源码与输出都是 UTF-8。于是 `已启动` 被当成 GBK 解读，
// 显示成 `锛堣鍒欓泦` 这类乱码 —— 程序本身没错，是两边编码没谈拢。
//
// 修法：进程启动时把控制台代码页切成 UTF-8（65001）。
//
// 不论 stdout 是否被重定向都设置 —— 重定向时设置它没有副作用
// （写出去的字节本来就与控制台代码页无关），但控制台窗口本身
// 会跟着变，那正是用户双击时看的那个窗口。
//
// 为什么不用宽字符输出：不必。控制台代码页设为 65001 后，
// 直接写 UTF-8 字节就是正确路径，改动面最小。

#ifndef AI2048_CORE_CONSOLE_H_
#define AI2048_CORE_CONSOLE_H_

namespace ai2048 {

/**
 * 把控制台代码页切到 UTF-8，使中文在双击运行时正常显示。
 *
 * 必须在**任何输出之前**调用。非 Windows 平台是空操作。
 * 被重定向时该调用无副作用，字节保持 UTF-8 原样。
 */
void EnableUtf8Console();

}  // namespace ai2048

#endif  // AI2048_CORE_CONSOLE_H_
