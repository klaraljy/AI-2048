// 局面评估：expectimax 的叶子函数。
//
// 这里**不使用游戏真实分数**作为评分项。
// 真实分数会过度鼓励"立刻合并"，而 2048 里延迟合并往往收益更大
// （nneonneo 的原话：the actual score ... is too heavily weighted in favor of
// merging tiles when delayed merging could produce a large benefit）。
//
// 评分项都是"局面形状"的度量：
//   empty        空格数 —— 最基础的一条，没有空格就没有腾挪空间
//   monotonicity 单调性 —— 行/列上的牌按数值单调排列
//   smoothness   平滑度 —— 相邻牌的数值接近
//   merge        合并潜力 —— 相邻等值对的数量
//   corner       最大牌靠角
//   snake        蛇形权重 —— 把"单调 + 大牌在角 + 无孔洞"编码成一个模板
//
// 权重来自公开的调参结论（nneonneo / xificurk 用 CMA-ES 调出来的量级），
// 本项目后续会用固定的种子集自己再调一轮。

#ifndef AI2048_AI_EVALUATE_H_
#define AI2048_AI_EVALUATE_H_

#include <cstdint>

#include "core/board.h"

namespace ai2048 {

// 权重来自**本项目自己的种子集扫描**（见 docs/results/），不是照抄公开值。
//
// 调优过程记录（depth 4，40 局，seeds-v1）：
//   初始值（照公开论文量级拍的）        18,023
//   mono 47 -> 250                     30,825   ← 单调性是最大的杠杆
//   empty 270 -> 400                   34,121
//   merge 18 -> 30                     34,363
// 反面记录（都试过且更差，不要再走回头路）：
//   snake 放大到 2.0 / 6.0             13,797 ~ 17,703
//   empty 降到 150                     23,500
//   empty_late 降到 600 / 800          29,104 ~ 30,076
//   mono 超过 320                      27,043
struct Weights {
  // 空格越多越好。残局每一格都更珍贵，所以 empty_late 用于空格很少时。
  //
  // ⚠️ empty_late **不要调小**：降到 600/800 会明显变差 ——
  // 残局阶段的空间比早期更值钱，这个直觉是对的。
  //
  // ⚠️ **`empty` 这个权重对"决策"几乎没有影响**（2026-09-13 实测）：
  // 用决策影响力探针（同一局面下各候选走子的差异）测，
  // `empty=200` 与 `empty=900` 得到的决策占比都是 5.4~5.5%。
  // 原因：空位数的原始散布本来就小（走一步只变 ±1），加大权重只是把总分
  // 整体抬高一个常数，**不改变走子选择**。所以想让"保空间"参与决策，
  // 该调的是 `empty_late`（残局的倍率），不是 `empty`。
  float empty = 400.0F;

  // ⚠️ **实测：提到 1400 是负面的，已回退到 700**（2026-09-13）。
  //
  // 决策影响力探针确实显示 1400 让"空位"参与决策的比例从 5.4% 升到 10.9% ——
  // 但**影响力升上去不等于分数更高**：30 局配对对拍实测 −8.1%（t = −0.80），
  // 组合对照里更明显：旧值（late=700）51,880 vs late=1400 那一侧 35,563。
  //
  // **这条教训比数值本身重要**：探针测的是"这一项在多大程度上影响走子"，
  // 而**"影响更大"既可能是好事也可能是坏事** —— 它只说明该项有权重，
  // 不说明该权重的方向对。merge 那次之所以成立，是因为它从 0.7% 这种
  // "几乎没有影响"提到了 17%；而这里是从"已有影响"继续加大。
  //
  // 原始扫描（旧格局）也只测过"调小更差"，没测过上限 —— 现在补上了：上限就是 700。
  float empty_late = 700.0F;
  int empty_late_threshold = 3;

  // 单调性：按牌面等级加权，让"大数字不单调"被重罚。
  // **这是本项目里最大的一个杠杆**（47 -> 250 带来 71% 的提升）。
  // 直觉：2048 的分数几乎完全由"能不能维持一条单调的链"决定，
  // 而单调性项正是唯一直接度量这件事的项。
  float monotonicity = 250.0F;

  // 平滑度：相邻牌数值接近。
  //
  // ⚠️ **量级注意**：它的原始值平均只有 36，而 `monotonicity` 是 5.6、
  // `merge` 是 1.3 —— 各项原始量级差了两个数量级，所以这些权重数字
  // **不能直接比较大小**，要看"决策权重"（见 AGENTS.md 的标定一节）。
  float smoothness = 32.0F;

  // 合并潜力：相邻等值对的数量。
  //
  // ⚠️ **这个权重被量级问题坑了很久。** 它的原始值平均只有 1.3（相邻等值对
  // 本来就少），所以写 30 的时候它对决策的**影响力只有 0.7%** —— 等于不存在。
  // 但它的**区分度**很高（散布/均值 = 1.47，仅次于单调性的 1.77）：
  // 它是少数能区分"能合"与"不能合"的项。
  //
  // 用 tools/calibration/influence_probe.cpp 量出"区分度高但影响力为零"之后
  // 重标定，实测（seeds-v1 前 40 局、depth 4、配对比较）：
  //
  //     30 → 750    +24.5%   （43,573 → 54,253，t = 2.13）
  //   750 → 1500   **−33.9%**（54,253 → 35,860，t = −3.93）
  //
  // 是**单峰**且峰很陡，750 附近最好。要再细化就在 400~1100 之间扫。
  float merge = 750.0F;

  // 最大牌靠角的奖励（按空格数缩放）。
  // 注意：单调性项已经隐含了"大牌靠角"（角是单调链的端点），
  // 所以这一项调大反而有害（试过 5000/6000，都更差）。
  float corner = 2200.0F;

  // 蛇形权重：把整盘牌按一条蛇形路径加权求和。
  //
  // 量级 15 是**实测扫出来的最优点**（d4、seeds-v1 各 100 局）：
  //     8 → 38,870   12 → 39,790   **15 → 42,792**   18 → 40,966   22 → 39,096
  // 是单峰，15 附近最好；再大就压过短期合并的收益了。
  //
  // 早期这里写的是 1.5 并且注释说"放大反而变差" —— 那个结论建立在**错误的实现**上：
  // 当时只有一套锚定左上角的模板（最大块在别的角时模板就是错的），
  // 而且用指数相加（大牌之间几乎无差别）。修成"四角模板 + 自动选锚点 + 用实际值"
  // 之后，这一项成了本项目**最大的一个杠杆**：34,934 → 42,792（+22.5%）。
  float snake = 15.0F;

  // 位置排名蛇形分：沿蛇形路径的**指数衰减**位置权重（见 evaluate.cpp 的
  // SnakeRankScore）。
  //
  // 与上面的 snake 是两件事，不要混：
  //   snake       = 1..16 **线性**权重 × 牌的**数值** —— 只惩罚"大牌不在路径上"
  //   snake_rank  = 0.5^rank **指数**权重 × 牌的**指数** —— 惩罚"大牌位置错误"
  //
  // 线性权重的区分度太弱：一张 1024 从路径头挪到尽头只差 15,360，
  // 乘上 snake 的系数 0.015 后对总分影响约 230，相对上万的总分几乎无感。
  //
  // ⚠️ 默认 0：**新项一律先关着**，否则 42,792 那套历史基准全部不可比。
  // 验证有效后才会给非零权重。
  float snake_rank = 0.0F;

  // 最大牌本身的等级奖励，鼓励往高处走。
  //
  // ⚠️ 实测**关掉更好**（42,792 vs 41,719）：蛇形项已经内含了
  // "大牌越大越好"（高权重格 × 大牌值），这一项是重复计权。
  // 保留字段是为了便于对照实验，默认置 0。
  float max_tile = 0.0F;

  // ---------------------------------------------------------------------------
  // 下面三项是参考 JS 原型后补的（原型有，我们之前没有）
  // ---------------------------------------------------------------------------

  // 锚点控制：最大牌到"离它最近的角"的曼哈顿距离。
  // 距离 0 给满额奖励，越远扣得越狠。
  //
  // 为什么需要它：单调性只看**行/列内部的形状**，看不到"最大牌在整个棋盘上的位置"。
  // 一个盘面可以每行都单调，但最大牌在中间 —— 那种局面很容易被堵死。
  //
  // ⚠️ 旧实测（**merge 还是 30 的旧格局**）：100 略优于 300，600 已经变差
  // （34,363 → 36,522 → 36,423 → 34,517）。调大到 1400 会掉到 18,746。
  //
  // 2026-09-13 在**新格局**（merge=750）下重测：100 → 600 的 30 局配对对拍
  // 结论是「**分辨不出差异**」（−8.1%，t = −0.80）。所以旧结论在新格局下
  // 不再成立，但也**没有证据支持提高它** —— 保持 100（保守）。
  //
  // ⚠️ **不要用"决策影响力低"来论证该提高它。** 探针显示它的区分度 0.78、
  // 只占 0.9% 影响力，看起来与当初的 merge 是同一个模式；但实测提高后
  // 没有收益。**"影响力低"只说明它说话少，不说明它说错了方向。**
  float corner_control = 100.0F;

  // 边支撑：锚点所在行与列上的牌面等级之和。
  //
  // ⚠️ **实测有害，默认关闭。** 连 10 都会让平均分从 34,363 掉到 29,549。
  // 原因推测：它与单调性、梯度在信息上高度重叠，等于给同一件事加倍计权，
  // 反而淹没了合并潜力等短期项。保留字段是为了记录这个结论。
  float edge_support = 0.0F;

  // 梯度：行内按位置递减加权求和。
  //
  // ⚠️ **实测基本无收益，默认极小值。** 4 会让分数掉到 28,270。
  // 与单调性高度重叠。
  float gradient = 0.0F;

  // 根节点的锚点方向偏好（把最大牌推向最近的角）。
  //
  // ⚠️ **实测有害，默认关闭。** bias=20 时 36,522 → 33,296。
  // 原因推测：搜索出来的值比手工方向偏置更可靠，额外加偏置等于往结果里掺噪声。
  float anchor_bias = 0.0F;

  // ---------------------------------------------------------------------------
  // 下面两项按《AI算法设计2》补入（文档明确列出、而本项目先前没有）
  //
  // 两项都**默认 0**：新项一律先关着，用同一批种子测出效果再给权重 ——
  // 历史基准（42,792 那套）都是在没有它们的情况下测的，默认打开会让基准全部作废。
  // ---------------------------------------------------------------------------

  // 可移动性：还有几个方向能走（0~4）。
  //
  // 这是**最直接的死局预警** —— 空位多不代表安全，如果四个方向都被堵死，
  // 空位再多也是死。其它项（空位/单调性/平滑度）都只看静态形状，看不到这一层。
  //
  // 用**平方**放大末尾的稀缺性：4→3 个方向无所谓，2→1 才是真的危险。
  float mobility = 0.0F;

  // 孤立块：与任何邻居既不相等、也不差一倍的牌（即"参与不了任何合并链"）。
  //
  // 与平滑度不同：平滑度看的是"整盘落差总和"，会被大量正常相邻对稀释；
  // 这一项只数**真正卡住**的牌，所以能专门惩罚"角落里塞了个 2、周围全是大牌"
  // 这种单点破坏。文档把它列为独立的惩罚项。
  float islands = 0.0F;

  // ---------------------------------------------------------------------------
  // 按"合并的**价值**"加权的合并潜力（与上面的 merge 是两件事）
  // ---------------------------------------------------------------------------
  //
  //   merge       = 相邻等值对的**数量**         → 每一对都算 1
  //   merge_value = 相邻等值对的**结果牌值**之和  → 按 √(结果牌值) 加权
  //
  // 想法：2048 的**实际得分**就是合并出来的牌值（合两个 512 得 1024 分，
  // 合两个 4 只得 8 分），所以"能合出多大的牌"看起来比"能合几对"更贴近真目标。
  //
  // ⚠️ **实测否掉了这个想法，默认 0。** 在**同等决策影响力**（各约 17%）下
  // 正面对比（seeds-v1 前 40 局、depth 4、配对比较）：
  //
  //     merge   = 750（数对）      54,253
  //     mergeval= 320（按价值）    41,470    **−23.6%**，t = −2.50
  //
  // **为什么"数对"反而更好**：每一对可合并的邻接都是一个**潜在的腾挪出口**，
  // 所以"对数"其实是在度量**空间的可用程度**；而按价值加权会把 AI 推向
  // "为了攒一个大合并而牺牲灵活性"，在 2048 里那通常正是输棋的方式。
  //
  // 保留实现与这段结论的理由：这是个**干净的反例**，而且代价不低（一轮对拍 20 分钟）。
  // tests/evaluate_test.cpp 锁住了它的语义，防止有人以后又"顺手把它打开"。
  float merge_value = 0.0F;
};

// 评估一个局面（**不走子**的局面，即 chance 节点之下的状态）。
[[nodiscard]] float Evaluate(std::uint64_t board, const Weights& weights) noexcept;

/**
 * 切换单调性是否跳过空位，并**重建行查表**。**仅供标定工具使用。**
 *
 * 存在的唯一目的是把这个"修复"当成一次权重改动来对拍：
 * 跳过空位会整体抬高单调性总分，等价于隐式放大 `monotonicity` 权重，
 * 所以必须能一键切回旧行为做单变量对照。
 */
void SetMonotonicitySkipsEmptyForTesting(bool skip_empty);

// 可移动方向数，取值 0~4。0 表示死局。
//
// 独立导出（不只是 Weights::mobility 的内部实现）是因为**搜索深度**也要用它：
// 只剩 1~2 个方向可走时局面已经很危险，值得多搜几层，而这时空位数可能还很多 ——
// 只看空格的旧策略会误判成"宽松"反而减深度。详见 AdaptiveDepth。
[[nodiscard]] int CountMobility(std::uint64_t board) noexcept;

// 供调试面板使用的分项拆解。
struct EvaluationBreakdown {
  int empty_cells = 0;
  float empty = 0.0F;
  float monotonicity = 0.0F;
  float smoothness = 0.0F;
  float merge = 0.0F;
  /** 按结果牌值加权的合并潜力（与 merge 是两个独立的项，见 Weights 的说明）。 */
  float merge_value = 0.0F;
  float corner = 0.0F;
  float snake = 0.0F;
  float snake_rank = 0.0F;
  float max_tile = 0.0F;
  float corner_control = 0.0F;
  float edge_support = 0.0F;
  float gradient = 0.0F;
  int mobility_directions = 0;
  int island_tiles = 0;
  float mobility = 0.0F;
  float islands = 0.0F;
  float total = 0.0F;
};

[[nodiscard]] EvaluationBreakdown EvaluateWithBreakdown(std::uint64_t board,
                                                        const Weights& weights) noexcept;

}  // namespace ai2048

#endif  // AI2048_AI_EVALUATE_H_
